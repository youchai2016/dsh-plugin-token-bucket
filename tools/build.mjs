import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
// The bundle is a single scope: strip module syntax and rely on declaration order.
// Imports may span lines (readable import lists), so match the whole statement.
const inline = file => read(file)
  .replace(/^import[\s\S]*?from\s+['"][^'"]+['"];?[ \t]*\n/gm, '')
  .replace(/^export /gm, '');
const manifest = JSON.parse(read('package.json'));
const { version } = manifest;

const remote = read('lib/remote.js');
const exportsBlock = /\nexport \{([^}]+)\};?\s*$/;
const expectedExports = ['BUCKET_SNAPSHOT_SCHEMA', 'BUCKET_WATCH_DESCRIPTOR', 'TYPERT_REMOTE'];
const exportedNames = remote.match(exportsBlock)?.[1].split(',').map(name => name.trim()).filter(Boolean).sort();
if (JSON.stringify(exportedNames) !== JSON.stringify(expectedExports)) {
  throw new Error('Unexpected bridge contract exports; refusing a broken bundle');
}
const contract = `const BucketBridgeContract=(()=>{${remote.replace(exportsBlock, '')}\nreturn {${expectedExports.join(',')}};})();`;

const css = read('src/bucket.css');
const common = `const CSS=${JSON.stringify(css)};\n${inline('src/i18n.js')}\n${inline('src/bucket.js')}\n${inline('src/widget.js')}\n`;

fs.mkdirSync(path.join(root, 'lib'), { recursive: true });
fs.mkdirSync(path.join(root, 'preview'), { recursive: true });
fs.writeFileSync(path.join(root, 'lib/client.js'),
  `// Generated by tools/build.mjs. Reads one balance stream over the existing authenticated connection.\nwindow.__ModuleLoader__.load({id:'dsh-plugin-token-bucket',factory:function(require){\n'use strict';\n${common}\n${contract}\n${inline('src/bridge-client.js')}\n${inline('src/adapter.js')}\nreturn createPlugin(require, CSS);\n}});\n`);

fs.writeFileSync(path.join(root, 'preview/runtime.js'),
  `// Generated from the same model and widget as the DSH plugin.\n(function(){'use strict';\n${common}\nwindow.BucketPet={BucketWidget,freshState,applySnapshot,viewOf,persistedOf,restoreState,parseAmount,formatCents,POLL,DEFAULTS,css:CSS};\n})();\n`);

// Host-side strict reflection: authored, but shipped next to the contract it describes.
const reflection = read('src/typert.host.js');
if (!reflection.includes(`package: '${manifest.name}'`) || !reflection.includes('BUCKET_WATCH_DESCRIPTOR')) {
  throw new Error('Host reflection does not describe this package; refusing a broken bundle');
}
fs.copyFileSync(path.join(root, 'src/typert.host.js'), path.join(root, 'lib/typert.host.js'));

// Single-file preview works offline and in a browser with file://, no dev server required.
const runtime = fs.readFileSync(path.join(root, 'preview/runtime.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
const html = read('src/preview.html')
  .replaceAll('__PACKAGE_VERSION__', version)
  // A function replacement keeps the runtime literal: a currency symbol like '$' must
  // never be expanded as a replacement pattern such as `$'`.
  .replace('/*__RUNTIME__*/', () => runtime);
fs.writeFileSync(path.join(root, 'preview/index.html'), html);
console.log(`Built ${process.argv.includes('--preview-only') ? 'offline preview only' : 'client bundle and offline preview'}; v${version}.`);
